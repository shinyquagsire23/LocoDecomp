//
// ⚠ Ghidra's decompiler is BADLY WRONG on this function and must not be used as the model: it
// mis-reads the `push ecx` local-slot reservation, so the 4-byte result slot at [esp+0x10]
// never appears (every arm reads `return 0`, when the real epilogue is `mov eax,[esp+0x10]`)
// and the `category` parameter surfaces as a bogus `unaff_retaddr`. It also drops two blocks as
// unreachable. The frame was re-derived by hand from the raw disasm.
//
// One lever DID pay and is baked in: NetSessionEventQueue::nPlacedObjectCount is UNSIGNED, not
// `int`. The case -1 arm is the only site in the codebase that can tell the two models apart --
// `rand() % nPlacedObjectCount` emits an unsigned `xor edx,edx; div` in the original, where an
// `int` field promotes it to a signed `cdq; idiv`. The retype was measured repo-wide and is
// byte-neutral everywhere else (zero per-file changes), and it makes the field agree with its
// sibling dwReadyBigObjCount.
// Lever measured and REFUTED (do not re-run): hoisting the loop locals (i/nTarget/nSeen) out of
// the per-case blocks to function scope, VC5-old-for-scope style, is BYTE-IDENTICAL -- VC5's
// allocator is live-range based, not scope based (the same finding as v461's own scoping probe).
// See docs/PARKED.md.
// FUNCTION: LOCO 0x41e1f0
void *NetSessionEventQueue::PickRandomBigObjByCategory(int category) {
    void *pResult = 0;
    int nCount = 0;

    switch (category) {
    case -1:
        if (nPlacedObjectCount != 0) {
            pResult = pEvents.GetAt(rand() % nPlacedObjectCount);
        }
        break;

    case 0:
    case 1:
    case 4: {
        unsigned int i;
        for (i = 0; i < pEvents.Count(); i++) {
            QueuedBigObjItemPartial *pItem = (QueuedBigObjItemPartial *)pEvents.GetAt(i);
            BigObj *pDesc = (BigObj *)pItem->pKindDesc;
            unsigned char cat = (pDesc == 0) ? 0 : pDesc->categoryByte;
            if (cat == 3 && pItem->dwTrackState == 3 &&
                (category == 4 || pItem->pOwningTrain == (void *)category)) {
                nCount++;
            }
        }
        if (nCount != 0) {
            int nTarget;
            if (nCount >= 1) {
                nTarget = RAND_RANGE_MAYBE(1, nCount);
            } else {
                nTarget = RAND_RANGE_MAYBE(nCount, 1);
            }
            int nSeen = 0;
            for (i = 0; i < pEvents.Count(); i++) {
                if (nSeen == nTarget) {
                    break;
                }
                QueuedBigObjItemPartial *pItem = (QueuedBigObjItemPartial *)pEvents.GetAt(i);
                BigObj *pDesc = (BigObj *)pItem->pKindDesc;
                unsigned char cat = (pDesc == 0) ? 0 : pDesc->categoryByte;
                if (cat == 3 && pItem->dwTrackState == 3 &&
                    (category == 4 || pItem->pOwningTrain == (void *)category)) {
                    nSeen++;
                    pResult = pItem;
                }
            }
        }
        break;
    }

    case 3: {
        unsigned int i;
        for (i = 0; i < pEvents.Count(); i++) {
            QueuedBigObjItemPartial *pItem = (QueuedBigObjItemPartial *)pEvents.GetAt(i);
            BigObj *pDesc = (BigObj *)pItem->pKindDesc;
            unsigned char cat = (pDesc == 0) ? 0 : pDesc->categoryByte;
            if (cat == 3 && pDesc->IsType0x63aInSet()) {
                nCount++;
            }
        }
        if (nCount != 0) {
            int nTarget;
            if (nCount >= 1) {
                nTarget = RAND_RANGE_MAYBE(1, nCount);
            } else {
                nTarget = RAND_RANGE_MAYBE(nCount, 1);
            }
            int nSeen = 0;
            for (i = 0; i < pEvents.Count(); i++) {
                if (nSeen == nTarget) {
                    break;
                }
                QueuedBigObjItemPartial *pItem = (QueuedBigObjItemPartial *)pEvents.GetAt(i);
                BigObj *pDesc = (BigObj *)pItem->pKindDesc;
                unsigned char cat = (pDesc == 0) ? 0 : pDesc->categoryByte;
                if (cat == 3 && pDesc->IsType0x63aInSet()) {
                    nSeen++;
                    pResult = pItem;
                }
            }
        }
        break;
    }

    case 2:
        if (dwReadyBigObjCount != 0) {
            unsigned int nTarget;
            if (dwReadyBigObjCount >= 1) {
                nTarget = RAND_RANGE_MAYBE(1, dwReadyBigObjCount);
            } else {
                nTarget = RAND_RANGE_MAYBE(dwReadyBigObjCount, 1);
            }
            unsigned int nSeen = 0;
            unsigned int i;
            for (i = 0; i < pEvents.Count(); i++) {
                if (nSeen == nTarget) {
                    break;
                }
                QueuedBigObjItemPartial *pItem = (QueuedBigObjItemPartial *)pEvents.GetAt(i);
                // sic: no null guard on pKindDesc here, unlike every other arm.
                if (((BigObj *)pItem->pKindDesc)->bCountedInReadyBigObjCount != 0) {
                    nSeen++;
                    pResult = pItem;
                }
            }
        }
        break;

    default: {
        BigObj *pDesc = (BigObj *)g_UIResources.TileKind_GetOrLoadDescriptor(category);
        if (pDesc != 0 && pDesc->nLiveInstanceCountMaybe != 0) {
            int nTarget;
            if (pDesc->nLiveInstanceCountMaybe >= 1) {
                nTarget = RAND_RANGE_MAYBE(1, pDesc->nLiveInstanceCountMaybe);
            } else {
                nTarget = RAND_RANGE_MAYBE(pDesc->nLiveInstanceCountMaybe, 1);
            }
            int nSeen = 0;
            unsigned int i;
            for (i = 0; i < pEvents.Count(); i++) {
                if (nSeen == nTarget) {
                    break;
                }
                QueuedBigObjItemPartial *pItem = (QueuedBigObjItemPartial *)pEvents.GetAt(i);
                // sic: no null guard on pKindDesc here either.
                if (((BigObj *)pItem->pKindDesc)->resourceId == category) {
                    nSeen++;
                    pResult = pItem;
                }
            }
        }
        break;
    }
    }
    return pResult;
}

