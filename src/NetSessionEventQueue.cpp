// Board rebuild from the placed-object registry (declared on the class in
// NetSessionEventQueue.h; callers: TutorialWnd::OnExit's default arm and
// BuildToolButton::HandleMenuCommandMaybe): dirty-mark the board, play UI sound 0x5026,
// clear both effect-spawner lists and tear down every peer-train slot, then -- bracketed by
// a placement-cursor capture grab/release -- walk pEvents handing each entry to
// WorldBoardMaybe::FlushQueuedBigObjMaybe. A successful flush EVICTS the entry and
// decrements nPlacedObjectCount, so the index only advances on failure; every time the
// draining count crosses a multiple of 10 the loop runs one EffectSpawner tick plus a full
// UpdateDirtyTiles pass (progressive repaint during the rebuild).
void NetSessionEventQueue::RebuildBoardFromPlacedObjectsMaybe()
{
    g_worldBoard.bBoardDirtyNeedsRebuildFlag = 1;
    g_UIResources.PlayUiSound(0x5026);
    EffectSpawner_ClearBothListsMaybe(&DAT_004fd220);
    g_PeerTrainSlotQueue.TeardownAllSlotsMaybe();
    if (nPlacedObjectCount != 0) {
        PlacementCursorMaybe_004854c8.SetCursorCapture(1, 1, 1);
        int i = 0;
        while (i != (int)nPlacedObjectCount) {
            TilePlacedObj *pItem = (TilePlacedObj *)pEvents.GetAt(i);
            if (nPlacedObjectCount % 10 != 0) {
                if (g_worldBoard.FlushQueuedBigObjMaybe(pItem, 0) == 0) {
                    i++;
                }
            } else {
                if (g_worldBoard.FlushQueuedBigObjMaybe(pItem, 1) == 0) {
                    i++;
                }
                DAT_004fd220.EffectSpawner_TickMaybe();
                g_worldBoard.UpdateDirtyTiles(0);
            }
        }
        PlacementCursorMaybe_004854c8.SetCursorCapture(1, 1, 0);
    }
}

